# Run the benchmark suite of `benchmarks.jl` and write a Markdown report.
#
#     julia --project=benchmark benchmark/run.jl [output.md]
#
# The report (default `benchmark/RESULTS.md`) lists the median time of every benchmark,
# normalized per attempt, per particle or per pair, with its allocations, and compares
# the 2D soft sphere numbers with the original script (`baseline/RESULTS.md`). Set
# `SWAPMC_BENCH_SECONDS` to change the time budget per benchmark (default 3 s). The whole
# run takes a few minutes. Run it on an otherwise idle machine, on AC power and with the
# performance power profile: on battery (low-power profile) every number doubles.

using BenchmarkTools: BenchmarkTools, tune!, leaves
using InteractiveUtils: versioninfo
using Printf: @sprintf
using Statistics: median

include(joinpath(@__DIR__, "benchmarks.jl"))

"""
Numbers of the original script from `baseline/RESULTS.md` (ns per attempt), keyed by the
number of particles: `mc_step!` displacements only, swaps only, the 0.8/0.2 mix, and the
"as-is" main loop (`mc_step!` plus `total_energy` after every attempt).
"""
const ORIGINAL = Dict(
    1000 => (displacement=923.0, swap=1889.0, mixed=1117.0, asis=3.07e5),
    10_000 => (displacement=939.0, swap=1896.0, mixed=1142.0, asis=3.35e6),
)

"""
    baseline_ratios(key, ns) -> (vs_original, vs_asis)

Speed-ups of the benchmark `key` with normalized time `ns` with respect to the original
script, as strings (`"—"` where there is no comparable number).
"""
function baseline_ratios(key::AbstractVector{<:AbstractString}, ns::Real)
    none = ("—", "—")
    first(key) == "PolySoftSphere 2D" || return none
    m = match(r"^N=(\d+)$", key[2])
    m === nothing && return none
    ref = get(ORIGINAL, parse(Int, m.captures[1]), nothing)
    ref === nothing && return none
    fmt(x) = @sprintf("%.1f×", x)
    leaf = last(key)
    leaf == "displacement" && return fmt(ref.displacement / ns), "—"
    leaf == "swap" && return fmt(ref.swap / ns), "—"
    leaf == "sweep (0.8/0.2)" && return fmt(ref.mixed / ns), fmt(ref.asis / ns)
    return none
end

"""
    format_ns(x) -> String

Human readable number of nanoseconds with about four significant digits.
"""
function format_ns(x::Real)
    x >= 1e5 && return @sprintf("%.3g", x)
    x >= 100 && return @sprintf("%.0f", x)
    x >= 10 && return @sprintf("%.1f", x)
    return @sprintf("%.2f", x)
end

"""
    machine_description() -> String

Julia version and CPU as reported by `versioninfo`.
"""
function machine_description()
    info = sprint(versioninfo)
    lines = filter(l -> occursin(r"Julia Version|CPU:|LLVM:|Commit", l), split(info, '\n'))
    return join(strip.(lines), "; ")
end

"""
    git_description() -> String

Short commit hash of the repository, marked `+dirty` if there are uncommitted changes.
"""
function git_description()
    dir = dirname(@__DIR__)
    try
        commit = readchomp(`git -C $dir rev-parse --short HEAD`)
        dirty = !isempty(readchomp(`git -C $dir status --porcelain -- src benchmark`))
        return dirty ? "$(commit)+dirty" : commit
    catch
        return "unknown"
    end
end

"""
    report(results) -> String

Markdown table of the benchmark `results`.
"""
function report(results)
    rows = String[]
    for (rawkey, trial) in sort!(collect(leaves(results)); by=first)
        key = String.(rawkey)
        (divisor, unit) = normalization(key)
        ns = median(trial).time / divisor
        (vs_orig, vs_asis) = baseline_ratios(key, ns)
        push!(
            rows,
            "| $(join(key, " / ")) | $(format_ns(ns)) | $(unit) | $(trial.allocs) | " *
            "$(trial.memory) | $(vs_orig) | $(vs_asis) |",
        )
    end
    header = """
    # Benchmark results

    Generated by `benchmark/run.jl` on $(Libc.strftime("%Y-%m-%d", time())) (commit $(git_description())).

    $(machine_description()); $(Threads.nthreads()) thread(s).

    Median times, normalized per attempt (moves; for the sweep the mean over the
    0.8/0.2 mix of displacements and swaps), per particle (`total_energy`,
    `rebuild_cells!`) or per pair (pair kernels). Allocations and memory are per
    evaluation (one attempt, one sweep, one call or one kernel loop). The last two
    columns compare with the original `swapmc.jl` (`baseline/RESULTS.md`, same 2D
    system): "vs original" uses `mc_step!` alone, "vs as-is" the original main loop,
    which also recomputes the total energy after every attempt. See `README.md` for the
    systems and the optimization log.

    | benchmark | median | unit | allocs | bytes | vs original | vs as-is |
    |:----------|-------:|:-----|-------:|------:|------------:|---------:|
    """
    return header * join(rows, "\n") * "\n"
end

function main()
    output = isempty(ARGS) ? joinpath(@__DIR__, "RESULTS.md") : ARGS[1]
    seconds = parse(Float64, get(ENV, "SWAPMC_BENCH_SECONDS", "3"))
    tune!(SUITE)
    results = run(SUITE; verbose=true, seconds=seconds)
    text = report(results)
    write(output, text)
    println(text)
    println("Written to ", output)
    return nothing
end

main()
