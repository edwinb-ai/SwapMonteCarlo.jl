"""
Directory of the markdown result tables.
"""
const RESULTS_DIR = joinpath(@__DIR__, "results")

"""
    block_stderr(x; min_blocks=32)

Standard error of the mean of a correlated time series with the Flyvbjerg–Petersen
blocking method: the largest estimate over the blocking levels that still have at least
`min_blocks` blocks (conservative). Same as the helper of the test suite.
"""
function block_stderr(x::AbstractVector; min_blocks::Int=32)
    y = collect(float.(x))
    se = std(y) / sqrt(length(y))
    while length(y) ÷ 2 >= min_blocks
        n = length(y) ÷ 2
        y = [(y[2k - 1] + y[2k]) / 2 for k in 1:n]
        se = max(se, std(y) / sqrt(n))
    end
    return se
end

"""
    integrated_time(x; min_blocks=32) -> Float64

Integrated autocorrelation time of the series `x` in units of its sampling interval,
`τ_int = (se_block / se_naive)² / 2`, from the blocked standard error. A series of
independent samples has `τ_int = 1/2`.
"""
function integrated_time(x::AbstractVector; min_blocks::Int=32)
    naive = std(x) / sqrt(length(x))
    return (block_stderr(x; min_blocks=min_blocks) / naive)^2 / 2
end

"""
    gamma_cdf_int(k, x)

CDF of the Gamma distribution with integer shape `k` and unit scale.
"""
function gamma_cdf_int(k::Integer, x)
    x <= 0 && return 0.0
    s = 0.0
    term = 1.0
    for j in 0:(k - 1)
        j > 0 && (term *= x / j)
        s += term
    end
    return 1 - exp(-x) * s
end

"""
    ks_stat(samples, cdf)

Kolmogorov–Smirnov statistic of `samples` against the continuous `cdf`.
"""
function ks_stat(samples, cdf)
    x = sort(samples)
    n = length(x)
    d = 0.0
    for (i, xi) in enumerate(x)
        F = cdf(xi)
        d = max(d, i / n - F, F - (i - 1) / n)
    end
    return d
end

"""
    ks_pvalue(d, n)

Asymptotic p-value of the Kolmogorov–Smirnov statistic `d` with `n` samples, with the
small-sample correction of Stephens, `λ = (√n + 0.12 + 0.11/√n) d`.
"""
function ks_pvalue(d, n)
    λ = (sqrt(n) + 0.12 + 0.11 / sqrt(n)) * d
    λ < 0.2 && return 1.0
    p = 0.0
    for k in 1:100
        p += 2 * (-1)^(k - 1) * exp(-2 * k^2 * λ^2)
    end
    return clamp(p, 0.0, 1.0)
end

"""
    fmt_pm(x, se; digits=4)

`x ± se` with `digits` decimals.
"""
fmt_pm(x, se; digits=4) = @sprintf("%.*f ± %.*f", digits, x, digits, se)

"""
    passfail(ok) -> String

Markdown cell for a pass/fail verdict.
"""
passfail(ok::Bool) = ok ? "pass" : "**FAIL**"

"""
    md_table(header, rows) -> String

Markdown table with the column titles `header` and the rows `rows` (vectors of strings).
"""
function md_table(header, rows)
    io = IOBuffer()
    println(io, "| ", join(header, " | "), " |")
    println(io, "|", join(fill("---", length(header)), "|"), "|")
    for r in rows
        println(io, "| ", join(r, " | "), " |")
    end
    return String(take!(io))
end

"""
    environment_lines(seed) -> Vector{String}

Lines describing the run: date, Julia and package versions, machine and seed.
"""
function environment_lines(seed)
    return [
        "- Date: $(Dates.format(Dates.now(), "yyyy-mm-dd HH:MM"))",
        "- Julia $(VERSION), SwapMonteCarlo v$(pkgversion(SwapMonteCarlo)), " *
        "$(Sys.cpu_info()[1].model), 1 thread",
        "- Base seed: $(seed) (StableRNG)",
    ]
end

"""
    write_results(name, title, sections...; seed, runtime)

Write the markdown file `results/<name>.md` made of a title, the run environment and
the `sections` (strings, in order), and print it. Returns the path.
"""
function write_results(name, title, sections...; seed, runtime)
    mkpath(RESULTS_DIR)
    path = joinpath(RESULTS_DIR, "$(name).md")
    io = IOBuffer()
    println(io, "# ", title, "\n")
    println(io, "Generated by `validation/$(name).jl`.\n")
    foreach(l -> println(io, l), environment_lines(seed))
    println(io, @sprintf("- Wall time: %.0f s\n", runtime))
    for s in sections
        println(io, rstrip(s), "\n")
    end
    text = String(take!(io))
    write(path, rstrip(text) * "\n")
    println(text)
    println("Written to ", path)
    return path
end

# Hard particles

"""
    npt_density(sim, nequil, nsweeps) -> (mean, se, τ, acceptance)

Equilibrate and run the NPT simulation `sim`; returns the mean density, its blocked
standard error, the integrated autocorrelation time of the density (sweeps) and the
acceptance rates of the production run.
"""
function npt_density(sim, nequil, nsweeps)
    equilibrate!(sim, nequil)
    reset_stats!(sim)
    ts = TimeSeries(Density())
    run!(sim, nsweeps; observers=ts)
    ρ = ts["density"]
    return mean(ρ), block_stderr(ρ), integrated_time(ρ), acceptance_rate(sim)
end

"""
    virtual_pressure_at(rng, sim, ρ, nequil, nsweeps; xis=(1e-2, 3e-3))
        -> Vector{Tuple{Float64,Float64}}

Virtual-compression pressure in NVT at density `ρ` for each compression `ξ ∈ xis`, as
`(mean, standard error)` pairs, starting from the configuration of the NPT simulation
`sim` (continued until its density is at least `ρ`, then expanded to `ρ`).
"""
function virtual_pressure_at(rng, sim, ρ, nequil, nsweeps; xis=(1e-2, 3e-3))
    sys0 = sim.system
    while density(sys0) < ρ
        run!(sim, 1)
    end
    N = length(sys0)
    D = length(first(positions(sys0)))
    box = box_for_density(Val(D), N, ρ)
    f = (volume(box) / volume(sys0.box))^(1 / D)
    sys = System(box, positions(sys0) .* f, diameters(sys0), HardSphere())
    nvt = Simulation(sys, NVT(1.0), Displacement(0.1) => 1.0; rng=rng)
    equilibrate!(nvt, nequil)
    ts = TimeSeries(map(xi -> VirtualPressure(; xi=xi), xis)...; schedule=Every(2))
    run!(nvt, nsweeps; observers=ts)
    return [(mean(p), block_stderr(p)) for p in ts.values]
end

